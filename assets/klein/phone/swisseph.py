def julday(year, month, day, hour=12.0, cal=1):
    """Gregorian calendar Julian day (Meeus, Astronomical Algorithms ch. 7), same as swe.julday for cal=GREG_CAL."""
    y, m = year, month
    if m <= 2:
        y -= 1; m += 12
    a = int(y / 100)
    b = 2 - a + int(a / 4) if cal == 1 else 0
    return int(365.25 * (y + 4716)) + int(30.6001 * (m + 1)) + day + b - 1524.5 + hour / 24.0


def _lookup(name, *args):
    key = _json.dumps([list(args), {}])
    table = _RECORDED.get(name, {})
    if key not in table:
        raise ValueError("Swiss Ephemeris needed for " + name + str(args) + ": the phone build only has Klein's fixed transit day. "
                         "Birth-date conditioning needs the PC server.")
    return table[key]


def calc_ut(jd, body, flags=0):
    r = _lookup("calc_ut", jd, body, flags)
    return (tuple(r[0]), r[1])


def get_ayanamsa_ut(jd):
    return _lookup("get_ayanamsa_ut", jd)


